/**
 * True when `pattern` — one ignore line — could match `samplePath`.
 *
 * A presence check is not enough for a negation: git applies the **last**
 * matching pattern, so a negation is effective only when no ignore line below
 * it matches the same path. Deciding that needs real gitignore glob semantics,
 * not a prefix comparison — a prefix test cannot see that `*.md` or
 * `**` + `/*.md`, placed after `!.qfai/evidence/coverage-depth-*.md`,
 * re-ignores exactly what the negation re-included.
 *
 * Implemented rules, the ones a real `.gitignore` uses:
 *
 * - a leading `/`, or any `/` before the final character, anchors the pattern
 *   to the file's directory; otherwise it matches at any depth;
 * - a trailing `/` names a directory, and a directory pattern also covers
 *   everything beneath it;
 * - the double-star form crosses `/`, a single `*` does not, and `?` matches
 *   one non-`/` character;
 * - `[0-9]`, `[!a-z]` and `[[:digit:]]` are character classes, not the literal
 *   brackets a blanket escape turned them into.
 *
 * Blank lines, comments and negations are not ignore lines and never match.
 */
export function gitignorePatternMatches(pattern: string, samplePath: string): boolean {
  const trimmed = pattern.trim();
  if (trimmed.length === 0 || trimmed.startsWith("#") || trimmed.startsWith("!")) {
    return false;
  }

  const withoutTrailingSlash = trimmed.endsWith("/") ? trimmed.slice(0, -1) : trimmed;
  // Per gitignore(5): a `/` anywhere but the end anchors the pattern.
  const anchored = withoutTrailingSlash.includes("/");
  const body = withoutTrailingSlash.replace(/^\//, "");
  if (body.length === 0) {
    return false;
  }

  const source = globToRegexSource(body);
  if (source === null) {
    return false;
  }

  // The trailing group is what makes a directory pattern cover its contents.
  const prefix = anchored ? "^" : "^(?:.*/)?";
  return new RegExp(`${prefix}${source}(?:/.*)?$`).test(samplePath.replace(/^\//, ""));
}

/** One literal character, safe to drop into a regular expression. */
function escapeLiteral(char: string): string {
  return /[.*+?^${}()|[\]\\]/.test(char) ? `\\${char}` : char;
}

/** One literal character, safe to drop inside a regular-expression class. */
function escapeInClass(char: string): string {
  return /[\]\\^]/.test(char) ? `\\${char}` : char;
}

/**
 * POSIX class names git's wildmatch accepts, as regular-expression class bodies.
 *
 * Measured, not assumed: `git check-ignore -v` names
 * `coverage-depth-spec-[[:digit:]]*.md` as the rule that ignores
 * `coverage-depth-spec-0001.md`.
 */
const POSIX_CLASSES: Readonly<Record<string, string>> = {
  alnum: "A-Za-z0-9",
  alpha: "A-Za-z",
  blank: " \\t",
  cntrl: "\\x00-\\x1f\\x7f",
  digit: "0-9",
  graph: "\\x21-\\x7e",
  lower: "a-z",
  print: "\\x20-\\x7e",
  punct: "!-/:-@\\[-`{-~",
  space: " \\t\\n\\r\\f\\v",
  upper: "A-Z",
  xdigit: "0-9A-Fa-f",
};

/**
 * One `[...]` bracket expression as a regular-expression class, or `null`.
 *
 * git matches these the way fnmatch does — a set, a range, a `!`- or
 * `^`-negated set, and the POSIX `[:digit:]` names — so escaping `[` and `]`
 * into literals made `.qfai/evidence/coverage-depth-spec-[0-9]*.md` a line
 * `git check-ignore -v` reports as the winner and this matcher reported as no
 * match at all. `null` is an unterminated `[`, which wildmatch aborts on: git
 * ignores nothing for such a line, and neither does this.
 *
 * No wildcard crosses `/` under `FNM_PATHNAME`, and a class such as `[!a]` or
 * `[.-9]` spans it, so the lookahead holds the separator out of every one.
 */
function bracketExpression(glob: string, open: number): { source: string; next: number } | null {
  let index = open + 1;
  const negated = glob[index] === "!" || glob[index] === "^";
  if (negated) {
    index += 1;
  }
  let body = "";
  while (index < glob.length) {
    const char = glob[index] ?? "";
    // A `]` before any content is that character, not the terminator.
    if (char === "]" && body.length > 0) {
      return { source: `(?!/)[${negated ? "^" : ""}${body}]`, next: index + 1 };
    }
    if (glob.startsWith("[:", index)) {
      const close = glob.indexOf(":]", index + 2);
      const named = close === -1 ? undefined : POSIX_CLASSES[glob.slice(index + 2, close)];
      if (named === undefined) {
        return null;
      }
      body += named;
      index = close + 2;
      continue;
    }
    if (char === "\\" && index + 1 < glob.length) {
      body += escapeInClass(glob[index + 1] ?? "");
      index += 2;
      continue;
    }
    // `-` is left bare: inside a class it is the range operator.
    body += char === "-" ? "-" : escapeInClass(char);
    index += 1;
  }
  return null;
}

/**
 * One gitignore glob as a regular-expression source, or `null` when no path
 * can match it.
 *
 * A scan rather than chained replacements, because a bracket expression is the
 * one construct whose contents obey a different alphabet from the text around
 * it — the `*` in `[*a]` is a literal asterisk and the `.` in `[.-9]` is a
 * range endpoint — and a blanket escape-then-replace pass cannot tell which
 * half of the pattern it is standing in.
 */
function globToRegexSource(glob: string): string | null {
  let source = "";
  let index = 0;
  while (index < glob.length) {
    const char = glob[index] ?? "";
    if (glob.startsWith("**/", index)) {
      source += "(?:.*/)?";
      index += 3;
      continue;
    }
    if (glob.startsWith("**", index)) {
      source += ".*";
      index += 2;
      continue;
    }
    if (char === "*" || char === "?") {
      source += char === "*" ? "[^/]*" : "[^/]";
      index += 1;
      continue;
    }
    if (char === "[") {
      const bracket = bracketExpression(glob, index);
      if (bracket === null) {
        return null;
      }
      source += bracket.source;
      index = bracket.next;
      continue;
    }
    // A backslash quotes the next character: git reads `\*` as an asterisk.
    if (char === "\\" && index + 1 < glob.length) {
      source += escapeLiteral(glob[index + 1] ?? "");
      index += 2;
      continue;
    }
    source += escapeLiteral(char);
    index += 1;
  }
  return source;
}

/**
 * One `.gitignore` file, with the directory whose subtree it governs.
 *
 * `dir` is repo-relative, POSIX-separated, and `""` for the file at the
 * repository root. Its patterns are written relative to that directory, which
 * is why the layer has to carry it: a bare `*` inside
 * `.qfai/evidence/.gitignore` excludes that directory's contents, not the whole
 * repository.
 */
export type GitignoreLayer = {
  dir: string;
  lines: readonly string[];
};

/**
 * True when `layers` — every `.gitignore` on the way down to `samplePath` —
 * leave it ignored.
 *
 * Two precedence rules, only the second of which a single root-file read got
 * right:
 *
 * - **the deepest file that matches wins.** Per gitignore(5), patterns read
 *   from a `.gitignore` deeper in the tree override those from a shallower one.
 *   `qfai init` still maintains a legacy `.qfai/evidence/.gitignore` whose
 *   first line is `*` (`cli/commands/init.ts#ensureLegacyEvidenceIgnoreNegations`),
 *   so on an adopting project the root managed block is not the last word on
 *   the governance records in either direction: the nested
 *   `!coverage-depth-*.md` re-includes a matrix the root ignored, and a nested
 *   re-ignore hides one the root re-included.
 * - **within one file the last matching pattern wins**, negations included.
 *
 * Ancestors are decided first because git never descends into an excluded
 * directory — a negation on a file inside one is unreachable, which is why the
 * managed block ignores `.qfai/evidence/*` (the contents) rather than the
 * directory. A layer deeper than the path being judged cannot contain it, so
 * the same walk also declines to read an ignore file git would never have
 * reached.
 *
 * `samplePath` is repo-relative and POSIX-separated.
 */
export function isPathIgnoredByLayers(
  layers: readonly GitignoreLayer[],
  samplePath: string,
): boolean {
  const normalized = samplePath.replace(/^\//, "");
  const segments = normalized.split("/").filter((segment) => segment.length > 0);
  const ordered = [...layers].sort((left, right) => layerDepth(left.dir) - layerDepth(right.dir));
  for (let depth = 1; depth < segments.length; depth += 1) {
    // No trailing slash: `.qfai/evidence/*` matches `.qfai/evidence/` — the
    // directory's own contents-pattern would otherwise read as excluding the
    // directory it exists to keep walkable.
    if (layeredVerdict(ordered, segments.slice(0, depth).join("/"))) {
      return true;
    }
  }
  return layeredVerdict(ordered, normalized);
}

/**
 * True when `lines` — one root-level `.gitignore` — leave `samplePath` ignored.
 *
 * The single-file case of {@link isPathIgnoredByLayers}. A caller that can meet
 * a project carrying nested ignore files has to use that one instead.
 */
export function isPathIgnored(lines: readonly string[], samplePath: string): boolean {
  return isPathIgnoredByLayers([{ dir: "", lines }], samplePath);
}

/** Directory nesting depth; the repository root (`""`) is 0. */
function layerDepth(dir: string): number {
  return dir.split("/").filter((segment) => segment.length > 0).length;
}

/** Deepest-matching-file-wins over one concrete path, each file answering only for its own subtree. */
function layeredVerdict(layers: readonly GitignoreLayer[], samplePath: string): boolean {
  let ignored = false;
  for (const layer of layers) {
    const dir = layer.dir.replace(/^\/+/, "").replace(/\/+$/, "");
    const prefix = dir.length === 0 ? "" : `${dir}/`;
    if (prefix.length > 0 && !samplePath.startsWith(prefix)) {
      continue;
    }
    const verdict = lastMatchVerdict(layer.lines, samplePath.slice(prefix.length));
    // `undefined` is "this file said nothing", which must not overwrite what a
    // shallower one decided; only a real match moves the standing verdict.
    if (verdict !== undefined) {
      ignored = verdict;
    }
  }
  return ignored;
}

/**
 * Last-pattern-wins over one concrete path; negations count as matches.
 *
 * `undefined` when no pattern in the file matched at all — distinct from
 * `false`, which is a negation actively re-including the path and therefore
 * something that must outrank whatever a shallower file said.
 */
function lastMatchVerdict(lines: readonly string[], samplePath: string): boolean | undefined {
  let verdict: boolean | undefined;
  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.length === 0 || trimmed.startsWith("#")) {
      continue;
    }
    const negated = trimmed.startsWith("!");
    // `gitignorePatternMatches` refuses a `!` line by design, so the negation is
    // matched on its body and its verdict inverted.
    if (!gitignorePatternMatches(negated ? trimmed.slice(1) : trimmed, samplePath)) {
      continue;
    }
    verdict = !negated;
  }
  return verdict;
}

/**
 * True when `lines` leave `samplePath` ignored, under git's own last-match rule.
 *
 * The whole file is walked and every matching line — ignore or negation — moves
 * the verdict, because git's answer is the LAST pattern that matches and not the
 * first. A presence test cannot produce that answer: `!/tmp/` placed after the
 * managed block contains the characters of the entry it cancels.
 *
 * Comments and blank lines are not patterns and never move the verdict, which is
 * the other half of why a text search is the wrong instrument here — a sentence
 * of prose mentioning a path is not an ignore of it.
 */
export function effectivelyIgnores(lines: readonly string[], samplePath: string): boolean {
  let ignored = false;
  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.length === 0 || trimmed.startsWith("#")) {
      continue;
    }
    const negated = trimmed.startsWith("!");
    // `gitignorePatternMatches` refuses a negation by design, so the `!` comes
    // off here and the verdict it sets is what carries the negation's meaning.
    const body = negated ? trimmed.slice(1) : trimmed;
    if (!gitignorePatternMatches(body, samplePath)) {
      continue;
    }
    ignored = !negated;
  }
  return ignored;
}

/**
 * The recommended entries `content` does not satisfy, for `QFAI-REVIEW-008`.
 *
 * One function because two readings of "satisfied" would drift. The `.qfai/**`
 * entries are literal paths under a directory QFAI owns, and a project that
 * ignores one from its own section satisfies the recommendation just as well —
 * so containment is the right question for them, and reporting a rule the author
 * already has would only push them to duplicate it.
 *
 * {@link ARTICLE_XI_TMP_ENTRY} is not like that, and containment answers the
 * wrong question for it. The entry is spelled unanchored while the block writes
 * the anchored `/tmp/`, so the substring `tmp/` is also inside a project's own
 * `src/tmp/` — a directory Article XI makes no claim about — inside prose that
 * merely mentions `tmp/`, and inside a later `!/tmp/` that cancels the ignore
 * outright. In all three the root staging area is still tracked while the notice
 * that exists to say so is suppressed. So this entry is decided by asking git's
 * question — is {@link ARTICLE_XI_TMP_SAMPLE_PATH} ignored once the whole file
 * has had its say — which both spellings of a real ignore still answer yes to.
 */
export function missingRecommendedGitignoreEntries(content: string): string[] {
  const lines = content.split(/\r?\n/);
  return QFAI_GITIGNORE_RECOMMENDED_ENTRIES.filter((entry) =>
    entry === ARTICLE_XI_TMP_ENTRY
      ? !effectivelyIgnores(lines, ARTICLE_XI_TMP_SAMPLE_PATH)
      : !content.includes(entry),
  );
}

/**
 * A concrete path the negation re-includes, for feeding
 * {@link gitignorePatternMatches}.
 *
 * A negation is itself a glob, and glob-vs-glob overlap has no cheap exact answer. The two
 * directions of error are NOT symmetric, and this docblock used to have it backwards: a false
 * "conflict" only re-appends a negation that was already last, which is where it belongs
 * anyway — but a MISSED conflict leaves a file git is ignoring outside version control, with
 * nothing to notice it afterwards.
 *
 * So the caller instantiates BOTH patterns and asks the question both ways round; see
 * {@link negationsOutrankLaterIgnores}.
 */
export function negationSamplePath(negation: string): string {
  const body = negation.replace(/^!/, "");
  // These globs are consumed only by canonical `*-spec-NNNN.md` records.
  // A generic `sample` did not overlap a later `implement-spec-*.md` rule,
  // so migration incorrectly treated a losing negation as effective.
  if (/(?:^|\/)(?:implement|atdd)-\*\.md$/.test(body)) {
    return body.replace(/\*\.md$/, "spec-0001.md");
  }
  const withContents = body.endsWith("/") ? `${body}sample` : body;
  return withContents.replace(/\*\*/g, "sample/leaf").replace(/\*/g, "sample");
}

/**
 * True when every one of `negations` is still the last word on the paths it
 * re-includes.
 *
 * `lines` is the whole file, not one block: a project that appended
 * `.qfai/evidence/*.md` **after** the managed block wins under git's
 * last-match rule, and a block-scoped check calls the negation effective while
 * `git check-ignore -v` names the project's line.
 */
export function negationsOutrankLaterIgnores(
  lines: readonly string[],
  negations: readonly string[],
): boolean {
  for (const negation of negations) {
    const at = lines.lastIndexOf(negation);
    if (at === -1) {
      return false;
    }
    const sample = negationSamplePath(negation);
    const negationBody = negation.replace(/^!/, "");
    for (let index = at + 1; index < lines.length; index += 1) {
      const later = lines[index] ?? "";

      // Direction 1: a path this negation re-includes, matched by the later ignore.
      if (gitignorePatternMatches(later, sample)) {
        return false;
      }

      // Direction 2: a path the later ignore covers, matched by this negation.
      //
      // Review finding [E1]. One direction decides overlap from ONE instance of the negation,
      // and two globs can overlap without that instance being in the intersection. Measured:
      // the negation `!.qfai/evidence/coverage-depth-*.md` instantiates as
      // `coverage-depth-sample.md`, and a project line `.qfai/evidence/coverage-depth-spec-*.md`
      // does not match it — while a real matrix, whose name carries a spec number, is matched
      // by both. The conflict went unseen, the block was left where it was, and the Coverage
      // Depth Matrix — a record this repository requires in version control — stayed ignored.
      //
      // Instantiating the LATER pattern and asking whether the negation covers it closes that
      // case: `coverage-depth-spec-sample.md` is matched by `coverage-depth-*.md`. Neither
      // direction alone is exact, and two are not exact either — but each one can only ADD
      // conflicts, and a false conflict costs a relocation that was harmless anyway.
      const trimmed = later.trim();
      if (trimmed.length === 0 || trimmed.startsWith("#") || trimmed.startsWith("!")) {
        continue;
      }
      if (gitignorePatternMatches(negationBody, negationSamplePath(trimmed))) {
        return false;
      }
    }
  }
  return true;
}
