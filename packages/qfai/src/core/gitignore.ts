/**
 * Shared constants for QFAI-managed .gitignore block.
 * Used by both `qfai init` (writer) and validators (reader).
 */

export const QFAI_GITIGNORE_MARKER = "# ── QFAI managed (generated by qfai init) ──";

/** Essential gitignore entries that must be present alongside the marker. */
export const QFAI_GITIGNORE_REQUIRED_ENTRIES: readonly string[] = [
  ".qfai/report/*",
  ".qfai/evidence/*",
  ".qfai/discussion/*",
  ".qfai/review/*",
  // Per-runtime state. Written by `qfai discussion use`,
  // `qfai atdd scaffold` (escalation counters), and any future
  // single-file state holder. The file header explicitly states
  // "NOT committed configuration"; without this entry every normal
  // CLI run leaves an untracked `.qfai/state.json` in the consumer
  // repo and makes it trivial to accidentally `git add .` and
  // commit local session pointers / counters.
  ".qfai/state.json",
] as const;

/**
 * Governance records that must stay in version control: Change Requests
 * carrying user approval, and durable decision records. `qfai init` writes
 * these negations after the ignore lines so the later pattern wins.
 *
 * They are deliberately NOT in `QFAI_GITIGNORE_REQUIRED_ENTRIES`: an existing
 * project whose `.gitignore` predates them must not start failing validation.
 */
export const QFAI_GITIGNORE_GOVERNANCE_NEGATIONS: readonly string[] = [
  "!.qfai/decisions/",
  "!.qfai/decisions/**",
  // The real durable-decision write target: `writeDecisionRecord` persists
  // `.qfai/evidence/decisions/<ISO8601-stamp>.json` (see
  // `core/decisionRecord.ts#DECISIONS_REL`). Git never descends into an
  // ignored directory, so `.qfai/evidence/*` must be undone for the directory
  // itself before its contents can be re-included.
  "!.qfai/evidence/decisions/",
  "!.qfai/evidence/decisions/**",
  "!.qfai/evidence/change-request-*.md",
  "!.qfai/evidence/decision-*.md",
] as const;

/** Lines removed from the managed block in previous versions; stripped during migration. */
export const QFAI_GITIGNORE_LEGACY_LINES: readonly string[] = [
  "!.qfai/report/README.md",
  "!.qfai/evidence/README.md",
  "!.qfai/discussion/README.md",
  "!.qfai/review/README.md",
  ".qfai/discussion/discussion-*/",
  "!.qfai/review/review-*/",
  "!.qfai/review/review-*/**",
] as const;

export const QFAI_GITIGNORE_BLOCK = [
  QFAI_GITIGNORE_MARKER,
  ".qfai/report/*",
  ".qfai/evidence/*",
  ".qfai/discussion/*",
  ".qfai/review/*",
  ".qfai/state.json",
  // Negations last: git applies the last matching pattern, so these re-include
  // the governance records the ignores above would otherwise swallow.
  ...QFAI_GITIGNORE_GOVERNANCE_NEGATIONS,
  "",
].join("\n");
