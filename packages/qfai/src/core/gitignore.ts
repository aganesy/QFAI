/**
 * Shared constants for QFAI-managed .gitignore block.
 * Used by both `qfai init` (writer) and validators (reader).
 */

export const QFAI_GITIGNORE_MARKER = "# ── QFAI managed (generated by qfai init) ──";

/** Essential gitignore entries that must be present alongside the marker. */
export const QFAI_GITIGNORE_REQUIRED_ENTRIES: readonly string[] = [
  ".qfai/report/*",
  ".qfai/evidence/*",
  ".qfai/discussion/*",
  ".qfai/review/*",
] as const;

/** Lines removed from the managed block in previous versions; stripped during migration. */
export const QFAI_GITIGNORE_LEGACY_LINES: readonly string[] = [
  "!.qfai/report/README.md",
  "!.qfai/evidence/README.md",
  "!.qfai/discussion/README.md",
  "!.qfai/review/README.md",
  ".qfai/discussion/discussion-*/",
  "!.qfai/review/review-*/",
  "!.qfai/review/review-*/**",
] as const;

export const QFAI_GITIGNORE_BLOCK = [
  QFAI_GITIGNORE_MARKER,
  ".qfai/report/*",
  ".qfai/evidence/*",
  ".qfai/discussion/*",
  ".qfai/review/*",
  "",
].join("\n");
