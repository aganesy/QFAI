type Rgba = { r: number; g: number; b: number; a: number };
type Dimension = { value: number; unit: "px" | "rem" };

function parseColor(css: string): Rgba | null {
  return parseHex(css) ?? parseRgb(css);
}

function parseHex(css: string): Rgba | null {
  const match = /^#([0-9a-fA-F]{3,8})$/.exec(css.trim());
  const digits = match?.[1];
  if (!digits || ![3, 4, 6, 8].includes(digits.length)) return null;
  const full = digits.length <= 4 ? digits.replace(/./g, "$&$&") : digits;
  const channel = (index: number): number => Number.parseInt(full.slice(index, index + 2), 16);
  return {
    r: channel(0),
    g: channel(2),
    b: channel(4),
    a: full.length === 8 ? channel(6) / 255 : 1,
  };
}

function parseRgb(css: string): Rgba | null {
  const match =
    /^rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*(?:,\s*(\d*\.?\d+)\s*)?\)$/.exec(
      css.trim(),
    );
  if (!match) return null;
  const [r, g, b] = [match[1], match[2], match[3]].map(Number);
  const a = match[4] === undefined ? 1 : Number(match[4]);
  if (r === undefined || g === undefined || b === undefined) return null;
  if ([r, g, b].some((value) => value > 255) || a > 1) return null;
  return { r, g, b, a };
}

function hexOf({ r, g, b, a }: Rgba): string {
  const pair = (value: number): string => value.toString(16).padStart(2, "0");
  const alpha = Math.round(a * 255);
  return `#${pair(r)}${pair(g)}${pair(b)}${alpha === 255 ? "" : pair(alpha)}`;
}

function colorValue(rgba: Rgba): Record<string, unknown> {
  return {
    colorSpace: "srgb",
    components: [rgba.r, rgba.g, rgba.b].map((value) => round(value / 255)),
    ...(rgba.a === 1 ? {} : { alpha: rgba.a }),
    hex: hexOf({ ...rgba, a: 1 }),
  };
}

function parseDimension(css: string): Dimension | null {
  if (css.trim() === "0") return { value: 0, unit: "px" };
  // CSS units are case-insensitive, so `40REM` is the token `40 rem`.
  const match = /^(\d+(?:\.\d+)?|\.\d+)(px|rem)$/i.exec(css.trim());
  const amount = match?.[1];
  const unit = match?.[2]?.toLowerCase();
  if (amount === undefined || (unit !== "px" && unit !== "rem")) return null;
  const value = Number(amount);
  return Number.isFinite(value) ? { value, unit } : null;
}

/** A length that may carry a sign, as a shadow's offsets and spread do. */
function parseSignedDimension(css: string): Dimension | null {
  const text = css.trim();
  const negative = text.startsWith("-");
  const dimension = parseDimension(/^[-+]/.test(text) ? text.slice(1) : text);
  if (!dimension || !negative || dimension.value === 0) return dimension;
  return { value: -dimension.value, unit: dimension.unit };
}

/** A CSS `box-shadow` as 2025.10 shadow objects, or null when a layer is not one this reads. */
function parseShadow(css: string): Record<string, unknown>[] | null {
  const layers: Record<string, unknown>[] = [];
  for (const layer of splitOutsideParens(css, ",")) {
    const parts = splitOutsideParens(layer, " ").filter((part) => part !== "");
    const inset = parts.includes("inset");
    const rest = parts.filter((part) => part !== "inset");
    const lengths = rest.map(parseSignedDimension);
    const colors = rest.map(parseColor);
    const lengthCount = lengths.filter((found) => found !== null).length;
    const colorIndex = colors.findIndex((found) => found !== null);
    const color = colors[colorIndex];
    if (!color || lengthCount < 2 || lengthCount > 4 || lengthCount + 1 !== rest.length) {
      return null;
    }
    const [offsetX, offsetY, blur, spread] = lengths.filter((found) => found !== null);
    // An offset or spread may be negative; a blur may not.
    if (blur !== undefined && blur.value < 0) return null;
    const zero: Dimension = { value: 0, unit: "px" };
    layers.push({
      color: colorValue(color),
      offsetX,
      offsetY,
      blur: blur ?? zero,
      spread: spread ?? zero,
      ...(inset ? { inset: true } : {}),
    });
  }
  return layers.length > 0 ? layers : null;
}

function shadowColors(design: DesignMd): string[] {
  return Object.values(design.visual.shadow).flatMap((css) =>
    splitOutsideParens(css, ",").flatMap((layer) =>
      splitOutsideParens(layer, " ").filter((part) => parseColor(part) !== null),
    ),
  );
}

function splitOutsideParens(text: string, separator: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let current = "";
  for (const character of text.trim()) {
    if (character === "(") depth += 1;
    if (character === ")") depth -= 1;
    if (depth === 0 && (character === separator || (separator === " " && /\s/.test(character)))) {
      parts.push(current.trim());
      current = "";
      continue;
    }
    current += character;
  }
  parts.push(current.trim());
  return parts;
}

/**
 * A font stack's family names, split on the commas outside quotes, with each name's quotes and
 * escapes taken off: `"ACME, Inc", sans-serif` is two names.
 */
function fontStack(stack: string): string[] {
  const families: string[] = [];
  let current = "";
  let quote: string | null = null;
  for (let index = 0; index < stack.length; index += 1) {
    const character = stack.charAt(index);
    if (character === "\\") {
      const escape = cssEscape(stack, index + 1);
      current += escape.text;
      index = escape.end - 1;
    } else if (quote !== null) {
      if (character === quote) quote = null;
      else current += character;
    } else if (character === '"' || character === "'") {
      quote = character;
    } else if (character === ",") {
      families.push(current.trim());
      current = "";
    } else {
      current += character;
    }
  }
  families.push(current.trim());
  return families.filter((family) => family !== "");
}

/**
 * The character a CSS escape after a backslash stands for, and where the escape ends: up to six
 * hex digits name a code point and take one following white space with them, as `\41 CME` is
 * `ACME`; any other character stands for itself.
 */
function cssEscape(text: string, start: number): { text: string; end: number } {
  const hex = /^[0-9a-fA-F]{1,6}/.exec(text.slice(start))?.[0];
  if (hex === undefined) return { text: text.charAt(start), end: start + 1 };
  let end = start + hex.length;
  if (text.startsWith("\r\n", end)) end += 2;
  else if (/^[ \t\n\r\f]/.test(text.charAt(end))) end += 1;
  const point = Number.parseInt(hex, 16);
  const valid = point > 0 && point <= 0x10ffff && (point < 0xd800 || point > 0xdfff);
  return { text: String.fromCodePoint(valid ? point : 0xfffd), end };
}

function hyphen(key: string): string {
  return key.replace(/_/g, "-");
}

function round(value: number): number {
  return Number(value.toFixed(4));
}

function setAt(tree: Record<string, unknown>, at: readonly string[], node: unknown): void {
  const parent = groupAt(tree, at.slice(0, -1));
  const last = at.at(-1);
  if (last !== undefined) parent[last] = node;
}

function groupAt(tree: Record<string, unknown>, at: readonly string[]): Record<string, unknown> {
  let group = tree;
  for (const part of at) {
    const next = group[part];
    if (isRecord(next)) {
      group = next;
      continue;
    }
    const created: Record<string, unknown> = {};
    group[part] = created;
    group = created;
  }
  return group;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

async function readOptional(file: string): Promise<string | null> {
  try {
    return await readFile(file, "utf-8");
  } catch (error: unknown) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return null;
    throw error;
  }
}
