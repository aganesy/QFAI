/**
 * The project's design catalogue: the tokens root `DESIGN.md` states, written as a token file in
 * the Design Tokens Community Group format (2025.10) and as the Tailwind 4 `@theme` block.
 *
 * `DESIGN.md` stays the file a person edits. `qfai catalog design` derives both files from it,
 * so code reads the theme instead of copying hex values by hand, and `qfai validate` reads them
 * back to warn when either no longer matches `DESIGN.md` and when UI source holds a hex value
 * that matches no token.
 */

import { readFile } from "node:fs/promises";
import path from "node:path";

import {
  COLOR_KEYS,
  decimalProductText,
  parseDesignMd,
  type DesignMd,
} from "../design/designMd.js";

/** Where the token file and the theme are written and read, relative to the project root. */
export const DESIGN_TOKENS_PATH = path.join(".qfai", "catalog", "design.tokens.json");
export const DESIGN_THEME_PATH = path.join(".qfai", "catalog", "theme.css");
export const ROOT_DESIGN_MD = "DESIGN.md";

const GENERATED =
  "Generated by `qfai catalog design` from DESIGN.md. Edit DESIGN.md, not this file, and run the command again.";

/** A token value in the 2025.10 format, or a JSON value carried as written. */
type TokenValue = string | number | string[] | Record<string, unknown> | Record<string, unknown>[];

/** One token: where it sits in the file, its value there, and its theme variable if any. */
type Token = {
  path: string[];
  type?: string;
  value: TokenValue;
  /** The `@theme` custom property and its CSS value; absent for a token the theme does not carry. */
  css?: { name: string; value: string };
};

/** A group-level `$description` and `$extensions`, for what DESIGN.md states but no token holds. */
type GroupNote = { path: string[]; description: string; extensions: Record<string, string> };

export type DesignSource =
  { state: "absent" } | { state: "invalid"; message: string } | { state: "read"; design: DesignMd };

export type GeneratedRead = { state: "absent" } | { state: "read"; text: string };

/** The root `DESIGN.md`, parsed. */
export async function readDesignSource(root: string): Promise<DesignSource> {
  const text = await readOptional(path.join(root, ROOT_DESIGN_MD));
  if (text === null) return { state: "absent" };
  const parsed = parseDesignMd(text);
  if ("error" in parsed) return { state: "invalid", message: parsed.error.message };
  return { state: "read", design: parsed.data };
}

/** A generated file as committed, if it exists. */
export async function readGenerated(root: string, relative: string): Promise<GeneratedRead> {
  const text = await readOptional(path.join(root, relative));
  return text === null ? { state: "absent" } : { state: "read", text };
}

/** The vendor namespace of the token file's `$extensions`, in reverse-domain form. */
export const EXTENSION_KEY = "dev.qfai";

/** How many tokens the token file holds for this design. */
export function countTokens(design: DesignMd): number {
  return tokensOf(design).filter((token) => token.type !== undefined).length;
}

/** The token file's text, byte-identical for the same `DESIGN.md` front matter. */
export function renderDesignTokens(design: DesignMd): string {
  const tree: Record<string, unknown> = { $description: GENERATED };
  for (const token of tokensOf(design)) {
    // A value no token type of the format states stays out of the file: a strict reader
    // rejects a token whose type it cannot work out. The theme still carries it.
    if (token.type === undefined) continue;
    const node: Record<string, unknown> = { $type: token.type };
    node.$value = token.value;
    setAt(tree, token.path, node);
  }
  for (const note of notesOf(design)) {
    const group = groupAt(tree, note.path);
    group.$description = note.description;
    group.$extensions = { [EXTENSION_KEY]: note.extensions };
  }
  return `${JSON.stringify(tree, null, 2)}\n`;
}

/** The Tailwind 4 theme's text: one `@theme` block of the tokens' custom properties. */
export function renderTheme(design: DesignMd): string {
  const lines = tokensOf(design).flatMap((token) =>
    token.css ? [`  ${token.css.name}: ${token.css.value};`] : [],
  );
  return [`/* ${GENERATED} */`, "@theme {", ...lines, "}", ""].join("\n");
}

/** Whether two generated texts are the same, line ends aside. */
export function sameGeneratedText(a: string, b: string): boolean {
  return a.replace(/\r\n/g, "\n") === b.replace(/\r\n/g, "\n");
}

/** Every colour the tokens hold, as lower-case `#rrggbb` or `#rrggbbaa`. */
export function tokenHexes(design: DesignMd): Set<string> {
  const hexes = new Set<string>();
  for (const value of [...Object.values(design.visual.colors), ...shadowColors(design)]) {
    const rgba = parseColor(value);
    if (rgba) hexes.add(hexOf(rgba));
  }
  return hexes;
}

/** A hex colour written in source text: its line, as written, and its normalised form. */
export type RawHex = { line: number; written: string; hex: string };

// A `#` that starts a hex literal: not inside a word, an entity, a URL path or a `url(#id)`
// reference, and not followed by more of a name.
const RAW_HEX_RE =
  /(?<![\w&#/(])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})(?![\w-])/g;
// Comments hold prose such as `// see #12ab`, so they are blanked before the scan. The `//` form
// is not read after a `:`, so the path of a URL such as `https://` is not taken for a comment.
const COMMENT_RE = /\/\*[\s\S]*?\*\/|<!--[\s\S]*?-->|(?<!:)\/\/[^\n]*/g;
/**
 * An attribute whose value is a colour: `style="color: #fff"`, `fill="#fff"`, React's
 * `stopColor="#fff"`, one Vue binds, `:fill="'#fff'"`, or a Svelte style directive,
 * `style:color="#fff"`. The name starts the line or follows whitespace, so `data-color="#fff"` is
 * another attribute. The value runs to the quote that opened it, so a quoted expression inside a
 * bound value is still part of it.
 */
const COLOR_ATTRIBUTE_RE =
  /(?:^|\s)(?:(?::|v-bind:)?(?:style|fill|stroke|color|stop-?color|flood-?color|lighting-?color)|style:[\w-]+)\s*=\s*\{?\s*(["'`])(?:(?!\1).)*$/i;
/**
 * Any other attribute's value, such as `aria-controls="#bad"`, Vue's `:href="'#bad'"` or a
 * Svelte directive such as `use:action="#bad"`: never a colour place. Written with no space around its `=`, a name reads as an attribute anywhere; with
 * spaces, as in `href = "#bad"`, only inside a tag opened on the same line, which keeps
 * `const accent = "#fff"` a whole string literal.
 */
const OTHER_ATTRIBUTE_RE =
  /(?:(?:^|\s)(?::|@|[\w-]+:)?[\w-]+=|<[A-Za-z][\w.:-]*(?:\s[^<>]*)?\s(?::|@|[\w-]+:)?[\w-]+\s*=\s*)\{?\s*(["'`])(?:(?!\1).)*$/;
/** A CSS declaration value: a `:` since the last `;`, `{` or `}` on the line. */
const DECLARATION_RE = /:[^:;{}]*$/;

/**
 * Every hex colour literal in a source file's text that sits where a colour goes: a CSS
 * declaration value, a colour attribute, or a whole string literal. A hex in prose, a comment,
 * an id selector or another attribute's value is not read as a colour.
 */
export function findRawHexes(text: string): RawHex[] {
  const scanned = text.replace(COMMENT_RE, (comment) => comment.replace(/[^\n]/g, " "));
  const found: RawHex[] = [];
  let line = 1;
  let counted = 0;
  for (const match of scanned.matchAll(RAW_HEX_RE)) {
    for (; counted < match.index; counted += 1) if (scanned[counted] === "\n") line += 1;
    const lineStart = scanned.lastIndexOf("\n", match.index - 1) + 1;
    const before = scanned.slice(lineStart, match.index);
    const end = match.index + match[0].length;
    const after = scanned.slice(end, end + 16);
    if (!colorPlace(before, after)) continue;
    const rgba = parseHex(match[0]);
    if (!rgba) continue;
    found.push({ line, written: match[0], hex: hexOf(rgba) });
  }
  return found;
}

/** Whether a hex sits where a colour goes, from the text before it on its line and after it. */
function colorPlace(before: string, after: string): boolean {
  if (COLOR_ATTRIBUTE_RE.test(before)) return true;
  if (OTHER_ATTRIBUTE_RE.test(before)) return false;
  if (/^\s*\{/.test(after)) return false;
  if (DECLARATION_RE.test(before)) return true;
  return /["'`]$/.test(before) && /^["'`]/.test(after);
}

