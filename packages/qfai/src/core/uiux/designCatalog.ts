/** Each semantic token, the colour key it aliases, and its path under `semantic`. */
const SEMANTIC_COLORS: readonly (readonly [string[], (typeof COLOR_KEYS)[number]])[] = [
  [["surface", "default"], "surface"],
  [["surface", "muted"], "surface_muted"],
  [["surface", "overlay"], "overlay"],
  [["text", "default"], "text"],
  [["text", "muted"], "text_muted"],
  [["border", "default"], "border"],
  [["primary", "default"], "primary"],
  [["status", "danger"], "danger"],
  [["status", "warning"], "warning"],
  [["status", "success"], "success"],
];

const FONT_FAMILIES = [
  ["sans", "family_sans"],
  ["display", "family_display"],
  ["mono", "family_mono"],
] as const;

function tokensOf(design: DesignMd): Token[] {
  const { visual } = design;
  const tokens: Token[] = COLOR_KEYS.map((key) =>
    colorToken(["color", hyphen(key)], visual.colors[key], `--color-${hyphen(key)}`),
  );
  for (const [semantic, key] of SEMANTIC_COLORS) {
    const primitive = `--color-${hyphen(key)}`;
    const name = `--color-${semantic.filter((part) => part !== "default").join("-")}`;
    tokens.push({
      path: ["semantic", ...semantic],
      type: "color",
      value: `{color.${hyphen(key)}}`,
      // A semantic name the theme already gives the primitive needs no second property.
      ...(name === primitive ? {} : { css: { name, value: `var(${primitive})` } }),
    });
  }
  for (const [name, key] of FONT_FAMILIES) {
    const stack = visual.typography[key];
    tokens.push({
      path: ["font", "family", name],
      type: "fontFamily",
      value: fontStack(stack),
      css: { name: `--font-${name}`, value: stack },
    });
  }
  for (const [name, size] of Object.entries(visual.typography.scale ?? {})) {
    tokens.push(dimensionToken(["font", "size", name], size, `--text-${name}`));
  }
  for (const [name, weight] of Object.entries(visual.typography.weight ?? {})) {
    tokens.push({
      path: ["font", "weight", name],
      type: "fontWeight",
      value: weight,
      css: { name: `--font-weight-${name}`, value: String(weight) },
    });
  }
  tokens.push(...spacingTokens(design));
  for (const [name, radius] of Object.entries(visual.radius)) {
    tokens.push(dimensionToken(["radius", name], radius, `--radius-${name}`));
  }
  for (const [name, shadow] of Object.entries(visual.shadow)) {
    tokens.push(shadowToken(["shadow", name], shadow, `--shadow-${name}`));
  }
  tokens.push(...layoutTokens(design));
  return tokens;
}

/**
 * `visual.layout` as tokens: each breakpoint and content width, and the smallest target in px.
 * `table_narrow` says how a table behaves, which no token type states, so it is left out.
 */
function layoutTokens(design: DesignMd): Token[] {
  const layout = design.visual.layout;
  if (layout === undefined) return [];
  const tokens: Token[] = [];
  for (const [name, width] of Object.entries(layout.breakpoints ?? {})) {
    tokens.push(dimensionToken(["layout", "breakpoint", name], width, `--breakpoint-${name}`));
  }
  for (const [name, width] of Object.entries(layout.content_max_width ?? {})) {
    tokens.push(
      dimensionToken(["layout", "content-max-width", name], width, `--container-${name}`),
    );
  }
  if (layout.target_min_px !== undefined) {
    tokens.push(
      dimensionToken(["layout", "target-min"], `${layout.target_min_px}px`, "--spacing-target-min"),
    );
  }
  return tokens;
}

/** `spacing.base` and each scale step as a multiple of it; Tailwind 4 needs only the base. */
function spacingTokens(design: DesignMd): Token[] {
  const spacing = design.visual.spacing;
  if (spacing?.base === undefined) return [];
  const base = spacing.base;
  const tokens = [dimensionToken(["spacing", "base"], base, "--spacing")];
  const unit = parseDimension(base);
  if (!unit) return tokens;
  for (const step of spacing.scale ?? []) {
    tokens.push({
      // A token name may not hold a `.`, so a step of 0.5 is named `0-5`.
      path: ["spacing", String(step).replace(".", "-")],
      type: "dimension",
      value: {
        value: Number(decimalProductText(base.trim().slice(0, -unit.unit.length), step)),
        unit: unit.unit,
      },
    });
  }
  return tokens;
}

/**
 * What DESIGN.md states that no token type holds: the data display formats.
 * They ride as text on their group, where a reader of the token file finds them beside the tokens.
 */
function notesOf(design: DesignMd): GroupNote[] {
  const notes: GroupNote[] = [];
  const display = design.data_display;
  if (display !== undefined && Object.keys(display).length > 0) {
    const extensions: Record<string, string> = {};
    for (const [key, value] of Object.entries(display)) extensions[key] = value;
    notes.push({
      path: ["data-display"],
      description:
        "How numbers, money and dates are written on screen, as DESIGN.md states. No CSS variable carries these.",
      extensions,
    });
  }
  return notes;
}

function colorToken(tokenPath: string[], css: string, cssName: string): Token {
  const rgba = parseColor(css);
  const property = { name: cssName, value: css };
  if (!rgba) return unrepresented(tokenPath, css, property);
  return { path: tokenPath, type: "color", value: colorValue(rgba), css: property };
}

function dimensionToken(tokenPath: string[], css: string, cssName: string): Token {
  const dimension = parseDimension(css);
  const property = { name: cssName, value: css };
  if (!dimension) return unrepresented(tokenPath, css, property);
  return { path: tokenPath, type: "dimension", value: dimension, css: property };
}

function shadowToken(tokenPath: string[], css: string, cssName: string): Token {
  const layers = parseShadow(css);
  const property = { name: cssName, value: css };
  if (!layers) return unrepresented(tokenPath, css, property);
  const [only] = layers;
  return {
    path: tokenPath,
    type: "shadow",
    value: layers.length === 1 && only ? only : layers,
    css: property,
  };
}

/**
 * A value the 2025.10 types cannot state, such as a length in `em` or `%`: kept as its CSS
 * text with no `$type`, so the theme still carries it and the token file leaves it out.
 */
function unrepresented(
  tokenPath: string[],
  css: string,
  property: NonNullable<Token["css"]>,
): Token {
  return {
    path: tokenPath,
    value: css,
    css: property,
  };
}

