/**
 * The project's component catalogue: every exported component the `uiux.surfacePaths` files
 * hold, with what its doc comment says about it.
 *
 * Parallel agents and later screens re-create a region that already exists when nothing lists
 * what exists. `qfai catalog components` writes the list as a committed file, and
 * `qfai validate` reads it back to warn about a component with no source, two components
 * realising one pattern, a raw element a listed component replaces, and a list out of date.
 *
 * The source is read with the `typescript` package the project installs, as the plain-text
 * check reads it, so qfai carries no JSX parser of its own.
 */

import { readFile } from "node:fs/promises";
import path from "node:path";

import { parse, stringify } from "yaml";

import type { QfaiConfig } from "../config.js";
import {
  loadTs,
  selectSurfaceFiles,
  type TsApi,
  type TsNode,
  type UiPlainTextOptions,
} from "../validators/uiPlainText.js";
import { readSafe } from "../validators/utils.js";

/** Where the catalogue is written and read, relative to the project root. */
export const COMPONENT_CATALOG_PATH = path.join(".qfai", "catalog", "components.yaml");

/** The raw elements a listed component can stand in for, named by its `@pattern`. */
export const REPLACEABLE_ELEMENTS = ["button", "input", "select"] as const;
type ReplaceableElement = (typeof REPLACEABLE_ELEMENTS)[number];

/** One exported component, as the catalogue lists it. */
export type CatalogComponent = {
  name: string;
  file: string;
  /** The members of its props type; absent when they cannot be read statically. */
  props?: string[];
  source?: string;
  reason?: string;
  states?: string[];
  pattern?: string;
  a11y?: string;
};

/** A raw `<button>`, `<input>` or `<select>` in a surface file. */
export type RawElement = { file: string; line: number; element: ReplaceableElement };

export type ComponentScan =
  | { readable: true; components: CatalogComponent[]; rawElements: RawElement[] }
  /** `unread` `.tsx`/`.jsx` files were selected but the project's `typescript` cannot be loaded. */
  | { readable: false; unread: number };

export type CatalogRead =
  | { state: "absent" }
  | { state: "invalid" }
  | { state: "read"; text: string; components: CatalogComponent[] };

const HEADER = [
  "# Generated by `qfai catalog components` from the files uiux.surfacePaths selects.",
  "# Edit a component's doc comment, not this file, and run the command again.",
  "",
].join("\n");

const DOC_TAGS = ["source", "reason", "states", "pattern", "a11y"] as const;

/**
 * Reads every exported component and every raw replaceable element in the `.tsx` and `.jsx`
 * files `uiux.surfacePaths` selects.
 */
export async function scanComponents(
  root: string,
  config: QfaiConfig,
  options: UiPlainTextOptions = {},
): Promise<ComponentScan> {
  const files = (await selectSurfaceFiles(root, config.uiux?.surfacePaths ?? [])).filter((file) =>
    [".tsx", ".jsx"].includes(path.extname(file)),
  );
  if (files.length === 0) return { readable: true, components: [], rawElements: [] };
  const ts = loadTs(root, options.loadTypescript);
  if (!ts) return { readable: false, unread: files.length };
  const components: CatalogComponent[] = [];
  const rawElements: RawElement[] = [];
  for (const file of files) {
    const read = componentsOfFile(ts, file, await readSafe(path.join(root, file)));
    components.push(...read.components);
    rawElements.push(...read.rawElements);
  }
  components.sort((a, b) => compare(a.file, b.file) || compare(a.name, b.name));
  return { readable: true, components, rawElements };
}

/** The catalogue file's text for a list of components, byte-identical for the same list. */
export function renderCatalog(components: readonly CatalogComponent[]): string {
  const entries = components.map((component) => {
    const entry: Record<string, string | string[]> = {
      name: component.name,
      file: component.file,
    };
    if (component.props) entry.props = component.props;
    for (const tag of DOC_TAGS) {
      const value = component[tag];
      if (value !== undefined) entry[tag] = value;
    }
    return entry;
  });
  return HEADER + stringify({ components: entries }, { lineWidth: 0 });
}

/** The committed catalogue, if there is one and it holds a list of components. */
export async function readCatalog(root: string): Promise<CatalogRead> {
  let text: string;
  try {
    text = await readFile(path.join(root, COMPONENT_CATALOG_PATH), "utf-8");
  } catch (error: unknown) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") {
      return { state: "absent" };
    }
    throw error;
  }
  let parsed: unknown;
  try {
    parsed = parse(text);
  } catch {
    return { state: "invalid" };
  }
  if (typeof parsed !== "object" || parsed === null || !("components" in parsed)) {
    return { state: "invalid" };
  }
  const list = parsed.components;
  if (!Array.isArray(list)) return { state: "invalid" };
  const components: CatalogComponent[] = [];
  for (const item of list) {
    const component = catalogComponentOf(item);
    if (!component) return { state: "invalid" };
    components.push(component);
  }
  return { state: "read", text, components };
}

/** Whether two catalogue texts are the same, line ends aside. */
export function sameCatalogText(a: string, b: string): boolean {
  return a.replace(/\r\n/g, "\n") === b.replace(/\r\n/g, "\n");
}

function catalogComponentOf(item: unknown): CatalogComponent | null {
  if (typeof item !== "object" || item === null) return null;
  const record = new Map<string, unknown>(Object.entries(item));
  const name = record.get("name");
  const file = record.get("file");
  if (typeof name !== "string" || typeof file !== "string") return null;
  const component: CatalogComponent = { name, file };
  const props = record.get("props");
  if (props !== undefined) {
    if (!isStringList(props)) return null;
    component.props = props;
  }
  const states = record.get("states");
  if (states !== undefined) {
    if (!isStringList(states)) return null;
    component.states = states;
  }
  for (const tag of ["source", "reason", "pattern", "a11y"] as const) {
    const value = record.get(tag);
    if (value === undefined) continue;
    if (typeof value !== "string") return null;
    component[tag] = value;
  }
  return component;
}

function isStringList(value: unknown): value is string[] {
  return Array.isArray(value) && value.every((entry) => typeof entry === "string");
}

function compare(a: string, b: string): number {
  if (a === b) return 0;
  return a < b ? -1 : 1;
}

/** The components and raw elements of one file. */
function componentsOfFile(
  ts: TsApi,
  file: string,
  source: string,
): { components: CatalogComponent[]; rawElements: RawElement[] } {
  const kind = path.extname(file) === ".jsx" ? ts.ScriptKind.JSX : ts.ScriptKind.TSX;
  const sourceFile = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, kind);
  const k = ts.SyntaxKind;
  const statements = sourceFile.statements ?? [];

  const localTypes = new Map<string, TsNode>();
  for (const statement of statements) {
    if (statement.kind === k.InterfaceDeclaration && statement.name) {
      localTypes.set(statement.name.getText(), statement);
    } else if (statement.kind === k.TypeAliasDeclaration && statement.name && statement.type) {
      localTypes.set(statement.name.getText(), statement.type);
    }
  }

  const containsJsx = (node: TsNode | undefined): boolean => {
    if (!node) return false;
    if (node.kind === k.JsxElement || node.kind === k.JsxSelfClosingElement) return true;
    if (node.kind === k.JsxFragment) return true;
    return node.getChildren().some(containsJsx);
  };
  // The function a `const` holds, directly or as the first function argument of a wrapping call
  // such as `memo(...)` or `forwardRef(...)`, however deeply the calls nest.
  const functionOf = (node: TsNode | undefined): TsNode | undefined => {
    if (!node) return undefined;
    if (node.kind === k.ArrowFunction || node.kind === k.FunctionExpression) return node;
    if (node.kind !== k.CallExpression) return undefined;
    for (const argument of node.arguments ?? []) {
      const found = functionOf(argument);
      if (found) return found;
    }
    return undefined;
  };
  // The member names of a props type: a literal, an interface or type alias the same file
  // declares, or an intersection of those. Ceiling: a type imported from another module, or a
  // part of an intersection declared elsewhere, contributes no names; resolving it through a
  // type checker over the whole program lifts this.
  const membersOf = (type: TsNode | undefined, seen: Set<string>): string[] | undefined => {
    if (!type) return undefined;
    if (type.kind === k.TypeLiteral || type.kind === k.InterfaceDeclaration) {
      return (type.members ?? [])
        .map((member) => member.name?.getText().replace(/^["']|["']$/g, ""))
        .filter((name): name is string => name !== undefined && name !== "");
    }
    if (type.kind === k.TypeReference && type.typeName) {
      const name = type.typeName.getText();
      if (seen.has(name)) return undefined;
      return membersOf(localTypes.get(name), new Set([...seen, name]));
    }
    if (type.kind === k.IntersectionType) {
      const parts = (type.types ?? []).map((part) => membersOf(part, seen));
      if (parts.every((part) => part === undefined)) return undefined;
      return parts.flatMap((part) => part ?? []);
    }
    return undefined;
  };
  const propsOf = (fn: TsNode | undefined, declared: TsNode | undefined): string[] | undefined => {
    const parameter = fn?.parameters?.[0];
    const fromParameter = membersOf(parameter?.type, new Set());
    if (fromParameter) return fromParameter;
    const binding = parameter?.name;
    if (binding && binding.kind === k.ObjectBindingPattern) {
      return (binding.elements ?? [])
        .filter((element) => element.dotDotDotToken === undefined)
        .map((element) => (element.propertyName ?? element.name)?.getText() ?? "")
        .filter((name) => name !== "");
    }
    // `const Button: FC<ButtonProps> = ...` names the props as the annotation's type argument.
    return membersOf(declared?.typeArguments?.[0], new Set());
  };
  const isExported = (statement: TsNode): boolean =>
    (statement.modifiers ?? []).some((modifier) => modifier.kind === k.ExportKeyword);

  const components: CatalogComponent[] = [];
  const add = (
    statement: TsNode,
    name: string | undefined,
    fn: TsNode | undefined,
    declared?: TsNode,
  ): void => {
    if (!name || !/^[A-Z]/.test(name) || !containsJsx(fn)) return;
    const props = propsOf(fn, declared);
    components.push({
      name,
      file,
      ...(props ? { props } : {}),
      ...docFields(source.slice(statement.pos, statement.getStart())),
    });
  };
  // Ceiling: a component exported by a separate `export { Name }` or `export default Name`
  // statement, and a class component, are not listed. Following the export list to its
  // declaration lifts the first; reading `render` methods lifts the second.
  for (const statement of statements) {
    if (!isExported(statement)) continue;
    if (statement.kind === k.FunctionDeclaration) {
      add(statement, statement.name?.getText(), statement);
    } else if (statement.kind === k.VariableStatement) {
      for (const declaration of statement.declarationList?.declarations ?? []) {
        const name = declaration.name;
        if (!name || name.kind !== k.Identifier) continue;
        add(statement, name.getText(), functionOf(declaration.initializer), declaration.type);
      }
    }
  }

  const rawElements: RawElement[] = [];
  const visit = (node: TsNode): void => {
    if (node.kind === k.JsxOpeningElement || node.kind === k.JsxSelfClosingElement) {
      const element = REPLACEABLE_ELEMENTS.find((name) => name === node.tagName?.getText());
      if (element) {
        const line = sourceFile.getLineAndCharacterOfPosition(node.getStart()).line + 1;
        rawElements.push({ file, line, element });
      }
    }
    for (const child of node.getChildren()) visit(child);
  };
  visit(sourceFile);
  return { components, rawElements };
}

/**
 * The catalogue fields the last `/** ... *\/` block before a declaration supplies. A tag runs
 * from `@name` to the next tag or the end of the block, its lines joined by single spaces;
 * `@states` is a comma list. Other tags and the description are not read.
 */
function docFields(trivia: string): Partial<CatalogComponent> {
  const block = /\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*$/.exec(trivia);
  if (!block) return {};
  const values = new Map<string, string>();
  let current: string | null = null;
  for (const rawLine of (block[1] ?? "").split(/\r?\n/)) {
    const line = rawLine.replace(/^\s*\*?\s?/, "").trim();
    const tag = /^@(\w+)\s*(.*)$/.exec(line);
    if (tag) {
      current = tag[1] ?? null;
      if (current !== null && !values.has(current)) values.set(current, tag[2] ?? "");
      else current = null;
      continue;
    }
    if (current !== null && line !== "") {
      values.set(current, `${values.get(current) ?? ""} ${line}`.trim());
    }
  }
  const fields: Partial<CatalogComponent> = {};
  for (const tag of DOC_TAGS) {
    const value = values.get(tag)?.trim();
    if (value === undefined || value === "") continue;
    if (tag === "states") {
      const states = value
        .split(",")
        .map((state) => state.trim())
        .filter((state) => state !== "");
      if (states.length > 0) fields.states = states;
    } else {
      fields[tag] = value;
    }
  }
  return fields;
}
