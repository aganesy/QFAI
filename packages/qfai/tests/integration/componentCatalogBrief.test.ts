/**
 * Acceptance of `qfai catalog components --brief`: the compact brief an agent's prompt carries,
 * made from the committed catalogue and run through the CLI entry.
 */

import {
  mkdir,
  mkdtemp,
  readdir,
  readFile,
  rm,
  symlink,
  truncate,
  writeFile,
} from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { afterEach, describe, expect, it } from "vitest";

import { runCliCaptured as cli } from "../helpers/cliCapture.js";

const roots: string[] = [];
const CATALOG = ".qfai/catalog/components.yaml";
const TOKENS = ".qfai/catalog/design.tokens.json";
const THEME = ".qfai/catalog/theme.css";

afterEach(async () => {
  while (roots.length > 0) {
    const root = roots.pop();
    if (root) await rm(root, { recursive: true, force: true });
  }
});

async function projectWith(files: Readonly<Record<string, string>>): Promise<string> {
  const root = await mkdtemp(path.join(os.tmpdir(), "qfai-component-brief-at-"));
  roots.push(root);
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(root, ...name.split("/"));
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, content, "utf-8");
  }
  return root;
}

/** Every file under the root with its text, so a run that writes nothing leaves it equal. */
async function snapshot(root: string): Promise<Record<string, string>> {
  const entries = await readdir(root, { recursive: true, withFileTypes: true });
  const files: Record<string, string> = {};
  for (const entry of entries) {
    if (!entry.isFile()) continue;
    const file = path.join(entry.parentPath, entry.name);
    files[path.relative(root, file).split(path.sep).join("/")] = await readFile(file, "utf-8");
  }
  return files;
}

const CATALOG_TEXT = [
  "# Generated by `qfai catalog components` from the files uiux.surfacePaths selects.",
  "components:",
  "  - name: Page",
  "    file: src/page.tsx",
  "  - name: Button",
  "    file: src/ui/button.tsx",
  "    props: [variant, size]",
  "    variants:",
  "      variant: [primary, ghost]",
  "      size: [sm, md]",
  "    source: shadcn/ui button@2.1",
  "    states: [default, disabled]",
  "    pattern: button",
  "    a11y: APG button, Enter and Space activate",
  "    tokens: [--color-primary]",
  "    realizes: [BR-UI-0003-0001]",
  "",
].join("\n");

const TOKENS_TEXT = JSON.stringify({
  $description: "Generated",
  color: {
    primary: { $type: "color", $value: "#123456" },
    surface: { $type: "color", $value: "#ffffff" },
  },
  spacing: { sm: { $type: "dimension", $value: { value: 4, unit: "px" } } },
});

// QFAI:AC-0001-0307-15
describe("the brief made from the committed catalogue", () => {
  // QFAI:EX-0001-0307-44
  it("prints one line per component and the design tokens, writing nothing", async () => {
    const root = await projectWith({
      [CATALOG]: CATALOG_TEXT,
      [TOKENS]: TOKENS_TEXT,
      [THEME]: "@theme {}\n",
    });
    const before = await snapshot(root);
    const first = await cli(["catalog", "components", "--brief"], root);
    expect(first.err).toBe("");
    expect(first.code).toBe(0);
    expect(first.out).toBe(
      [
        `Components in ${CATALOG}:`,
        "- Page (src/page.tsx)",
        "- Button (src/ui/button.tsx): pattern: button; states: default, disabled; props: variant, size; a11y: APG button, Enter and Space activate; variants: variant: primary | ghost, size: sm | md; source: shadcn/ui button@2.1; tokens: --color-primary; realizes: BR-UI-0003-0001",
        `Design tokens: 3 in ${TOKENS}; theme: ${THEME}`,
        "",
      ].join("\n"),
    );
    const second = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(second.out).toBe(first.out);
    expect(await snapshot(root)).toEqual(before);

    await rm(path.join(root, ...THEME.split("/")));
    await writeFile(path.join(root, ...TOKENS.split("/")), "{", "utf-8");
    const broken = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(broken.code).toBe(0);
    expect(broken.out.split("\n").at(-2)).toBe(
      `Design tokens: ${TOKENS} does not parse. Run \`qfai catalog design\`.`,
    );

    await rm(path.join(root, ...TOKENS.split("/")));
    const plain = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(plain.out).not.toContain("Design tokens");
  });

  // QFAI:EX-0001-0307-49
  it("keeps multiline catalogue text on its component's line", async () => {
    const root = await projectWith({
      [CATALOG]: CATALOG_TEXT.replace(
        "    a11y: APG button, Enter and Space activate",
        [
          "    a11y: |-",
          "      Enter activates the button.",
          "      Space also activates it.",
        ].join("\n"),
      ),
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(0);
    expect(brief.err).toBe("");
    const lines = brief.out.trimEnd().split("\n");
    expect(lines).toHaveLength(3);
    expect(lines[1]).toBe("- Page (src/page.tsx)");
    expect(lines[2]).toContain("a11y: Enter activates the button. Space also activates it.");
  });

  // QFAI:EX-0001-0307-49
  it("prints vertical tab, form feed and next line as spaces on the component's line", async () => {
    const root = await projectWith({
      [CATALOG]: CATALOG_TEXT.replace(
        "    a11y: APG button, Enter and Space activate",
        '    a11y: "Enter\\vactivates\\fit\\Nnow"',
      ),
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(0);
    const lines = brief.out.trimEnd().split("\n");
    expect(lines).toHaveLength(3);
    expect(lines[2]).toContain("a11y: Enter activates it now;");
  });

  // QFAI:EX-0001-0307-50
  it.each([
    { name: "a tab as a space", yaml: '"Enter\\tactivates"', shown: "a11y: Enter activates;" },
    {
      name: "an escape as its code point",
      yaml: '"Enter\\e[31m"',
      shown: "a11y: Enter\\u{001B}[31m;",
    },
    {
      name: "a bidi override as its code point",
      yaml: '"Enter\\u202Eok"',
      shown: "a11y: Enter\\u{202E}ok;",
    },
    {
      name: "a zero-width space as its code point",
      yaml: '"En\\u200Bter"',
      shown: "a11y: En\\u{200B}ter;",
    },
    {
      name: "a lone surrogate as its code point",
      yaml: '"En\\uD800ter"',
      shown: "a11y: En\\u{D800}ter;",
    },
    {
      name: "an astral format character as its five-digit code point",
      yaml: '"En\\U000E0001ter"',
      shown: "a11y: En\\u{E0001}ter;",
    },
  ])("prints $name on the component's line", async ({ yaml, shown }) => {
    const root = await projectWith({
      [CATALOG]: CATALOG_TEXT.replace(
        "    a11y: APG button, Enter and Space activate",
        `    a11y: ${yaml}`,
      ),
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(0);
    expect(brief.err).toBe("");
    const lines = brief.out.trimEnd().split("\n");
    expect(lines).toHaveLength(3);
    expect(lines[2]).toContain(shown);
  });

  // QFAI:EX-0001-0307-50
  it("prints non-ASCII text and escapes an emoji sequence's zero-width joiner", async () => {
    const root = await projectWith({
      [CATALOG]: CATALOG_TEXT.replace("  - name: Page", "  - name: Bouton–Été 🎉 👨\u200D👩 x"),
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(0);
    expect(brief.err).toBe("");
    const lines = brief.out.trimEnd().split("\n");
    expect(lines).toHaveLength(3);
    expect(lines[1]).toBe("- Bouton–Été 🎉 👨\\u{200D}👩 x (src/page.tsx)");
  });

  // QFAI:EX-0001-0307-49
  it("prints a numeric variant prop where the catalogue writes it", async () => {
    const root = await projectWith({
      [CATALOG]: CATALOG_TEXT.replace(
        "      size: [sm, md]",
        '      size: [sm, md]\n      "1": [a, b]',
      ),
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(0);
    expect(brief.out).toContain("variants: variant: primary | ghost, size: sm | md, 1: a | b;");
  });

  // QFAI:EX-0001-0307-49
  it("names the readable theme when the design token file is malformed", async () => {
    const root = await projectWith({
      [CATALOG]: CATALOG_TEXT,
      [TOKENS]: "{",
      [THEME]: "@theme {}\n",
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(0);
    expect(brief.err).toBe("");
    const lastLine = brief.out.trimEnd().split("\n").at(-1);
    expect(lastLine).toContain(`${TOKENS} does not parse`);
    expect(lastLine).toContain(THEME);
  });

  // QFAI:EX-0001-0307-49
  it("counts tokens in deeply nested groups", async () => {
    const groups = 12_000;
    const root = await projectWith({
      [CATALOG]: CATALOG_TEXT,
      [TOKENS]: '{"group":'.repeat(groups) + '{"token":{"$value":"value"}}' + "}".repeat(groups),
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(0);
    expect(brief.err).toBe("");
    expect(brief.out.trimEnd().split("\n").at(-1)).toBe(`Design tokens: 1 in ${TOKENS}`);
  });

  // QFAI:EX-0001-0307-45
  it("rejects cyclic additional catalogue fields in one line", async () => {
    const root = await projectWith({
      [CATALOG]:
        "components:\n  - name: Page\n    file: src/page.tsx\n    notes: &notes { self: *notes }\n",
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(1);
    expect(brief.out).toBe("");
    expect(brief.err.trimEnd().split("\n")).toHaveLength(1);
    expect(brief.err).toContain(`${CATALOG} is not a component catalogue`);
  });

  // QFAI:EX-0001-0307-45
  it.each([
    { name: "a sequence key", yaml: "? [p, q]\n      : x" },
    { name: "a null key", yaml: "~: x" },
  ])("rejects $name with one diagnostic", async ({ yaml }) => {
    const root = await projectWith({
      [CATALOG]: `components:\n  - name: Page\n    file: src/page.tsx\n    notes:\n      ${yaml}\n`,
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(1);
    expect(brief.out).toBe("");
    expect(brief.err.trimEnd().split("\n")).toHaveLength(1);
    expect(brief.err).toContain(`${CATALOG} is not a component catalogue`);
  });

  // QFAI:EX-0001-0307-49
  it("separates mapping keys that print alike", async () => {
    const root = await projectWith({
      [CATALOG]:
        'components:\n  - name: Page\n    file: src/page.tsx\n    variants: { 1: [a], "1": [b], x: [c] }\n',
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(0);
    expect(brief.out).toContain("- Page (src/page.tsx): variants: 1: a, 1: b, x: c\n");
  });

  // QFAI:EX-0001-0307-49
  it("separates component keys that print alike", async () => {
    const root = await projectWith({
      [CATALOG]: 'components:\n  - name: Page\n    file: src/page.tsx\n    1: [a]\n    "1": [b]\n',
    });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(0);
    expect(brief.out).toContain("- Page (src/page.tsx): 1: a; 1: b\n");
  });

  // QFAI:EX-0001-0307-45
  it("refuses a missing or invalid catalogue in one line and --brief with --check as a usage error", async () => {
    const root = await projectWith({});
    const absent = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(absent).toEqual({
      code: 1,
      out: "",
      err: `${CATALOG} does not exist. Run \`qfai catalog components\` and commit it.\n`,
    });

    await writeFile(path.join(root, "qfai.config.yaml"), "uiux: [\n", "utf-8");
    await mkdir(path.join(root, ".qfai", "catalog"), { recursive: true });
    await writeFile(path.join(root, ...CATALOG.split("/")), "components: 3\n", "utf-8");
    const invalid = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(invalid).toEqual({
      code: 1,
      out: "",
      err: `${CATALOG} is not a component catalogue. Run \`qfai catalog components\` and commit it.\n`,
    });

    const both = await cli(["catalog", "components", "--brief", "--check", "--root", root]);
    expect(both.code).toBe(2);
    expect(both.out).toContain("qfai catalog components");
    expect(both.err).toContain("qfai catalog components: give --brief or --check, not both.");

    expect((await cli(["catalog", "design", "--brief", "--root", root])).code).toBe(2);
  });

  // QFAI:EX-0001-0307-47
  it("names the one file it could not read, the catalogue or a design file", async () => {
    const couldNotRead = (file: string): RegExp =>
      new RegExp(`^qfai catalog components: could not read ${file.replace(/\./g, "\\.")}: .+\\n$`);
    const unreadable = await projectWith({});
    await mkdir(path.join(unreadable, ...CATALOG.split("/")), { recursive: true });
    const catalogue = await cli(["catalog", "components", "--brief", "--root", unreadable]);
    expect(catalogue.code).toBe(1);
    expect(catalogue.out).toBe("");
    expect(catalogue.err).toMatch(couldNotRead(CATALOG));

    for (const failing of [TOKENS, THEME]) {
      const root = await projectWith({ [CATALOG]: CATALOG_TEXT, [TOKENS]: TOKENS_TEXT });
      await rm(path.join(root, ...failing.split("/")), { force: true });
      await mkdir(path.join(root, ...failing.split("/")), { recursive: true });
      const run = await cli(["catalog", "components", "--brief", "--root", root]);
      expect(run.code).toBe(1);
      expect(run.out).toBe("");
      expect(run.err).toMatch(couldNotRead(failing));
    }
  });

  // QFAI:EX-0001-0307-47
  it("bounds design token reads and inspects theme presence without loading its text", async () => {
    const root = await projectWith({
      [CATALOG]: CATALOG_TEXT,
      [TOKENS]: TOKENS_TEXT,
      [THEME]: "",
    });
    const oversized = 8 * 1024 * 1024 + 1;
    await truncate(path.join(root, THEME), oversized);
    const args = ["catalog", "components", "--brief", "--root", root];
    const readable = await cli(args);
    expect(readable.code).toBe(0);
    expect(readable.out).toContain(`theme: ${THEME}`);

    await truncate(path.join(root, TOKENS), oversized);
    const rejected = await cli(args);
    expect(rejected.code).toBe(1);
    expect(rejected.out).toBe("");
    expect(rejected.err).toContain(`could not read ${TOKENS}: The file exceeds`);
  });

  // QFAI:EX-0001-0307-47
  it.each([TOKENS, THEME])("refuses a linked optional artifact %s", async (artifact) => {
    const root = await projectWith({ [CATALOG]: CATALOG_TEXT });
    const directory = path.join(root, "empty-directory");
    await mkdir(directory);
    await symlink(directory, path.join(root, artifact), "junction");

    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(1);
    expect(brief.out).toBe("");
    expect(brief.err.trimEnd().split("\n")).toHaveLength(1);
    expect(brief.err).toContain(`could not read ${artifact}: ${artifact} is a symbolic link`);
  });

  // QFAI:EX-0001-0307-47
  it.each([
    { name: "absent", tokenText: null },
    { name: "malformed", tokenText: "{" },
  ])("reports an unreadable theme when the token file is $name", async ({ tokenText }) => {
    const root = await projectWith({
      [CATALOG]: CATALOG_TEXT,
      ...(tokenText === null ? {} : { [TOKENS]: tokenText }),
    });
    await mkdir(path.join(root, ...THEME.split("/")), { recursive: true });
    const brief = await cli(["catalog", "components", "--brief", "--root", root]);
    expect(brief.code).toBe(1);
    expect(brief.out).toBe("");
    expect(brief.err.trimEnd().split("\n")).toHaveLength(1);
    expect(brief.err).toContain(`qfai catalog components: could not read ${THEME}: `);
  });

  // QFAI:EX-0001-0307-46
  it("ships the brief in the implementation UI guidance and the generator prompt", async () => {
    const skill = path.resolve(
      path.dirname(fileURLToPath(import.meta.url)),
      "..",
      "..",
      "assets",
      "init",
      ".qfai",
      "assistant",
      "skill",
    );
    const read = (relative: string): Promise<string> =>
      readFile(path.join(skill, ...relative.split("/")), "utf-8");
    const guidance = await read("qfai-implement/references/ui-affecting.md");
    const start = guidance.indexOf("## Component catalogue");
    const section = guidance.slice(start, guidance.indexOf("\n## ", start + 1));
    expect(section).toContain("`npx qfai catalog components --brief`");
    const prompt = await read("qfai-prototyping/references/generator-prompt.md");
    const order = prompt.slice(prompt.indexOf("## Read order"), prompt.indexOf("## HTML envelope"));
    expect(order).toContain("`npx qfai catalog components --brief`");
    expect(order).toContain("`.qfai/assistant/rule/references/base-components.yaml`");
  });
});
