/**
 * The design catalogue renderer: the token file and the theme it derives from a parsed
 * `DESIGN.md`, and the hex literals it reads from UI source.
 */

import { readFile } from "node:fs/promises";
import path from "node:path";

import { describe, expect, it } from "vitest";

import { parseDesignMd, type DesignMd } from "../../../src/core/design/designMd.js";
import {
  EXTENSION_KEY,
  countTokens,
  findRawHexes,
  renderDesignTokens,
  renderTheme,
  tokenHexes,
} from "../../../src/core/uiux/designCatalog.js";
import { getInitAssetsDir } from "../../../src/shared/assets.js";

const SAMPLE = path.join(
  getInitAssetsDir(),
  ".qfai",
  "assistant",
  "skill",
  "qfai-prototyping",
  "templates",
  "DESIGN.md.sample",
);

async function sampleDesign(edit: (text: string) => string = (text) => text): Promise<DesignMd> {
  const parsed = parseDesignMd(edit(await readFile(SAMPLE, "utf-8")));
  if ("error" in parsed) throw new Error(parsed.error.message);
  return parsed.data;
}

/** The node at a dotted path of the rendered token file. */
function tokenAt(design: DesignMd, at: string): unknown {
  let node: unknown = JSON.parse(renderDesignTokens(design));
  for (const part of at.split(".")) {
    node =
      typeof node === "object" && node !== null
        ? new Map(Object.entries(node)).get(part)
        : undefined;
  }
  return node;
}

describe("the token file and the theme", () => {
  // QFAI:EX-0001-0312-01
  it("states each token in the 2025.10 format and in the theme", async () => {
    const design = await sampleDesign();
    expect(tokenAt(design, "color.primary")).toEqual({
      $type: "color",
      $value: { colorSpace: "srgb", components: [0.1216, 0.1608, 0.2157], hex: "#1f2937" },
    });
    expect(tokenAt(design, "color.overlay.$value")).toMatchObject({ alpha: 0.5, hex: "#000000" });
    expect(tokenAt(design, "semantic.status.danger")).toEqual({
      $type: "color",
      $value: "{color.danger}",
    });
    expect(tokenAt(design, "semantic.surface.muted.$value")).toBe("{color.surface-muted}");
    expect(tokenAt(design, "font.family.sans.$value")).toEqual([
      "Inter",
      "system-ui",
      "sans-serif",
    ]);
    expect(tokenAt(design, "font.weight.bold")).toEqual({ $type: "fontWeight", $value: 700 });
    expect(tokenAt(design, "spacing.3.$value")).toEqual({ value: 0.75, unit: "rem" });
    expect(tokenAt(design, "radius.full.$value")).toEqual({ value: 9999, unit: "px" });
    expect(tokenAt(design, "shadow.sm")).toMatchObject({
      $type: "shadow",
      $value: {
        offsetX: { value: 0, unit: "px" },
        offsetY: { value: 1, unit: "px" },
        blur: { value: 2, unit: "px" },
        spread: { value: 0, unit: "px" },
        color: { alpha: 0.05, hex: "#0f172a" },
      },
    });
    expect(countTokens(design)).toBe(61);

    const theme = renderTheme(design);
    expect(theme.startsWith("/* Generated by `qfai catalog design` from DESIGN.md.")).toBe(true);
    for (const line of [
      "@theme {",
      "  --color-primary: #1F2937;",
      "  --color-surface-muted: #F3F4F6;",
      "  --color-status-danger: var(--color-danger);",
      "  --color-surface-overlay: var(--color-overlay);",
      "  --font-sans: Inter, system-ui, sans-serif;",
      "  --text-2xl: 1.5rem;",
      "  --font-weight-medium: 500;",
      "  --spacing: 0.25rem;",
      "  --radius-full: 9999px;",
      "  --shadow-sm: 0 1px 2px rgba(15,23,42,0.05);",
    ]) {
      expect(theme.split("\n")).toContain(line);
    }
    // A semantic alias the primitive already names gets no second property.
    expect(theme).not.toContain("var(--color-surface)");
    expect(theme.endsWith("}\n")).toBe(true);
    expect(renderDesignTokens(design)).toBe(renderDesignTokens(await sampleDesign()));
  });

  // QFAI:EX-0001-0312-01
  it("splits a font stack on the commas outside quotes, and drops each name's quotes", async () => {
    const design = await sampleDesign((text) =>
      text.replace(
        /family_sans: .*$/m,
        `family_sans: '"ACME, Inc", "Noto \\"Sans\\"", sans-serif'`,
      ),
    );
    expect(tokenAt(design, "font.family.sans.$value")).toEqual([
      "ACME, Inc",
      'Noto "Sans"',
      "sans-serif",
    ]);
    expect(renderTheme(design)).toContain(
      '  --font-sans: "ACME, Inc", "Noto \\"Sans\\"", sans-serif;\n',
    );
  });

  // QFAI:EX-0001-0312-02
  it("keeps a small spacing step and the overlay alpha as written, without float noise", async () => {
    const design = await sampleDesign((text) =>
      text
        .replace(/base: "0\.25rem"/, 'base: "0.00001rem"')
        .replace("scale: [0, 1, 2, 3, 4, 6, 8, 12, 16, 24]", "scale: [1, 3]")
        .replace('overlay:        "rgba(0,0,0,0.5)"', 'overlay:        "rgba(0,0,0,0.123456)"'),
    );
    expect(tokenAt(design, "spacing.1.$value")).toEqual({ value: 0.00001, unit: "rem" });
    expect(tokenAt(design, "spacing.3.$value")).toEqual({ value: 0.00003, unit: "rem" });
    expect(tokenAt(design, "color.overlay.$value")).toMatchObject({ alpha: 0.123456 });
  });

  // QFAI:EX-0001-0312-02
  it.each([
    ["0.123456789012345rem", 1, 0.123456789012345],
    ["0.1rem", 3, 0.3],
    ["0.25rem", 0.5, 0.125],
  ])("computes %s times %d on its decimal digits", async (base, step, expected) => {
    const design = await sampleDesign((text) =>
      text
        .replace(/base: "0\.25rem"/, `base: "${base}"`)
        .replace("scale: [0, 1, 2, 3, 4, 6, 8, 12, 16, 24]", `scale: [${step}]`),
    );
    expect(tokenAt(design, `spacing.${String(step).replace(".", "-")}.$value`)).toEqual({
      value: expected,
      unit: "rem",
    });
  });

  // QFAI:EX-0001-0312-02
  it("reads a length unit in any case as the lower-case token unit", async () => {
    const design = await sampleDesign((text) => text.replace('sm: "40rem"', 'sm: "40REM"'));
    expect(tokenAt(design, "layout.breakpoint.sm.$value")).toEqual({ value: 40, unit: "rem" });
    expect(renderTheme(design)).toContain("  --breakpoint-sm: 40REM;\n");
  });

  // QFAI:EX-0001-0312-02
  it("reads a negative shadow offset or spread, and leaves a negative blur to the theme", async () => {
    const spread = await sampleDesign((text) =>
      text.replace('sm: "0 1px 2px rgba(15,23,42,0.05)"', 'sm: "0 -2px 4px -1px #0a0a0a"'),
    );
    expect(tokenAt(spread, "shadow.sm.$value")).toMatchObject({
      offsetX: { value: 0, unit: "px" },
      offsetY: { value: -2, unit: "px" },
      blur: { value: 4, unit: "px" },
      spread: { value: -1, unit: "px" },
    });
    const blur = await sampleDesign((text) =>
      text.replace('sm: "0 1px 2px rgba(15,23,42,0.05)"', 'sm: "0 2px -4px #0a0a0a"'),
    );
    expect(tokenAt(blur, "shadow.sm")).toBeUndefined();
    expect(renderTheme(blur)).toContain("  --shadow-sm: 0 2px -4px #0a0a0a;\n");
  });

  // QFAI:EX-0001-0312-02
  it("leaves a value no token type states out of the token file and keeps it in the theme", async () => {
    const design = await sampleDesign((text) =>
      text
        .replace('md:   "0.5rem"', 'md:   "0.5em"')
        .replace("scale: [0, 1, 2, 3, 4, 6, 8, 12, 16, 24]", "scale: [0.5]"),
    );
    expect(tokenAt(design, "radius.md")).toBeUndefined();
    expect(tokenAt(design, "radius.sm")).toMatchObject({ $type: "dimension" });
    expect(renderTheme(design)).toContain("  --radius-md: 0.5em;\n");
    expect(tokenAt(design, "spacing.0-5.$value")).toEqual({ value: 0.125, unit: "rem" });
  });
});

describe("layout and data display tokens", () => {
  // QFAI:EX-0001-0312-03
  it("writes visual.layout as dimension tokens and the formats as group text", async () => {
    const design = await sampleDesign((text) =>
      text.replace(
        "accessibility:",
        ["data_display:", '  locale: "ja-JP"', '  date: "YYYY-MM-DD"', "accessibility:"].join("\n"),
      ),
    );
    expect(tokenAt(design, "layout.breakpoint.sm.$value")).toEqual({ value: 40, unit: "rem" });
    expect(tokenAt(design, "layout.breakpoint.xl.$value")).toEqual({ value: 80, unit: "rem" });
    expect(tokenAt(design, "layout.content-max-width.reading.$value")).toEqual({
      value: 42,
      unit: "rem",
    });
    expect(tokenAt(design, "layout.target-min.$value")).toEqual({ value: 44, unit: "px" });
    expect(JSON.stringify(tokenAt(design, "layout"))).not.toContain("stack");
    expect(tokenAt(design, "data-display.$extensions")).toEqual({
      [EXTENSION_KEY]: { locale: "ja-JP", date: "YYYY-MM-DD" },
    });
    const theme = renderTheme(design);
    for (const line of [
      "  --breakpoint-sm: 40rem;",
      "  --container-reading: 42rem;",
      "  --container-form: 36rem;",
      "  --spacing-target-min: 44px;",
    ]) {
      expect(theme).toContain(`${line}\n`);
    }
    expect(theme).not.toContain("stack");
  });
});

describe("hex literals in source", () => {
  // QFAI:EX-0001-0312-09
  it("reads a Vue bound attribute by its name: a colour one is a colour place, another is not", () => {
    const found = findRawHexes(
      [
        `<a :href="'#bad'">x</a>`,
        `<a v-bind:aria-controls="'#bad'">x</a>`,
        `<path :fill="'#12ab56'" />`,
        `<path v-bind:stroke="'#12ab56'" />`,
      ].join("\n"),
    );
    expect(found.map((hex) => hex.line)).toEqual([3, 4]);
  });

  // QFAI:EX-0001-0312-09
  it("reads React's camelCase colour attributes as colour places", () => {
    const found = findRawHexes(
      [
        '<stop stopColor="#12ab56" />',
        '<feFlood floodColor="#12ab56" />',
        '<feDiffuseLighting lightingColor="#12ab56" />',
      ].join("\n"),
    );
    expect(found.map((hex) => hex.line)).toEqual([1, 2, 3]);
  });

  // QFAI:EX-0001-0312-09
  it("reads an attribute written with spaces around its = inside a tag", () => {
    const found = findRawHexes(
      ['<a href = "#bad">x</a>', '<path fill = "#12ab56" />', 'const accent = "#12ab56";'].join(
        "\n",
      ),
    );
    expect(found.map((hex) => hex.line)).toEqual([2, 3]);
  });

  // QFAI:EX-0001-0312-09
  it("reads a colour attribute only by its whole name", () => {
    const found = findRawHexes(
      [
        '<rect data-color="#12ab56" />',
        '<rect data-fill="#12ab56" data-style="#12ab56" />',
        '<rect fill="#12ab56" />',
        'stroke="#12ab56"',
      ].join("\n"),
    );
    expect(found.map((hex) => hex.line)).toEqual([3, 4]);
  });

  // QFAI:EX-0001-0312-09
  it("reads each hex colour literal with its line, and skips anchors and longer names", () => {
    const found = findRawHexes(
      [
        'const a = "#1f2937";',
        "<div style={{ color: '#12ab56' }} />",
        "color: #FFF;",
        '<a href="#add">x</a>',
        "background: #00000080;",
        "&#123; #abcdefg #face-id url(/a#bad)",
      ].join("\n"),
    );
    expect(found).toEqual([
      { line: 1, written: "#1f2937", hex: "#1f2937" },
      { line: 2, written: "#12ab56", hex: "#12ab56" },
      { line: 3, written: "#FFF", hex: "#ffffff" },
      { line: 5, written: "#00000080", hex: "#00000080" },
    ]);
  });

  it("knows every colour and shadow colour DESIGN.md states", async () => {
    const hexes = tokenHexes(await sampleDesign());
    for (const hex of ["#1f2937", "#ffffff", "#00000080", "#0f172a0d"]) {
      expect(hexes.has(hex)).toBe(true);
    }
    expect(hexes.has("#12ab56")).toBe(false);
  });
});
