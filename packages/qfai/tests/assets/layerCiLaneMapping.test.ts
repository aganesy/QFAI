/**
 * The layer-to-CI-lane mapping document: where it lives, what it must disclaim, and what it
 * must not become.
 *
 * ## Why a sibling file rather than a section
 *
 * The layer-policy loader resolves `catalog/test-layers.md` by exact path and reads nothing
 * else in that directory. So a sibling catalog file is INVISIBLE to it, and a new section
 * inside the catalog would not be — the loader parses that file, and prose there can extract
 * as a token. That asymmetry is the whole reason the mapping is a separate document, and it is
 * what keeps the layer vocabulary from growing by accident.
 *
 * ## What the document must not turn into
 *
 * The layer catalog marks per-level routing as a target state, "not enforced, do not follow
 * yet". A mapping document that reads as activating it would put a reader at odds with the
 * live gate — `QFAI-ATDD-112` scans one directory, and a document telling them to annotate
 * elsewhere would produce work the gate cannot see. So the prose is constrained, not just the
 * vocabulary.
 *
 * ## The mirror direction
 *
 * `packages/qfai/assets/init/.qfai/...` is the authoring side and `.qfai/...` is generated by
 * `pnpm sync:ssot`. A change made only at the root is overwritten by the next sync and then
 * fails the tracked-tree diff, which is why the rows below assert the DIRECTION rather than
 * only the equality: two identical copies say nothing about which one is the source.
 */
